function base64ToHex(base64) {
  return [...atob(base64)]
    .map(c => c.charCodeAt(0).toString(16).padStart(2, '0'))
    .join('');
}

function hexToAscii(hex) {
  return hex.match(/.{1,2}/g)
    .map(byte => String.fromCharCode(parseInt(byte, 16)))
    .join('');
}

